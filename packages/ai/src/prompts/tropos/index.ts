/**
 * Επιστρέφει τις οδηγίες ύφους για έναν τρόπο εξέτασης (T4).
 *
 * Pure και ντετερμινιστικό: ίδιος τρόπος → ίδιες ακριβώς γραμμές. Σε άγνωστο
 * τρόπο (που δεν προέρχεται από το frozen enum) επιστρέφεται
 * `MI_EGKYRO_SXIMA` — ποτέ ψεύτικο περιεχόμενο με default ύφος.
 */
export function odos_tropou(tropos: TroposExetasis): Apotelesma<string[]> {
  const odigies = ODIGIES_TROPOY[tropos];
  if (odigies === undefined) {
    return apotyxia(
      'MI_EGKYRO_SXIMA',
      `Άγνωστος τρόπος εξέτασης «${String(tropos)}»· αναμενόμενο ένα από: ${TROPOI_EXETASIS.join(', ')}`
    );
  }
  return ok([...odigies, KANONAS_50_50, KANONAS_MI_EPINOIEIS]);
}

/**
 * Τυλίγει τις οδηγίες του τρόπου σε ενότητα κειμένου έτοιμη για ενσωμάτωση
 * στα prompts P1–P4 (ίδιο φορμάτ `## <τίτλος>` με τα υπόλοιπα).
 */
export function enotita_tropou(tropos: TroposExetasis): Apotelesma<string> {
  const odigies = odos_tropou(tropos);
  if (!odigies.ok) {
    return odigies;
  }
  return ok(
    enotita_se_keimeno(TITLOS_TROPOY, [
      `tropos: ${tropos}`,
      ...odigies.timi.map((o) => `- ${o}`),
    ])
  );
}
