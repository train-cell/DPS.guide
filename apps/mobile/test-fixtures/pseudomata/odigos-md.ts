/** Βρίσκει μια ενότητα από το συγκεκριμένο μάθημα ή διατρέχοντας όλα τα γνωστά μαθήματα. */
function vreis_enotita(enotita_id: string, kodikos?: string): Enotita | undefined {
  if (kodikos !== undefined) {
    return pare_xarti_mathimatos(kodikos).enotites.find((k) => k.id === enotita_id);
  }
  const apoProepilogi = pseudos_xartis().enotites.find((k) => k.id === enotita_id);
  if (apoProepilogi !== undefined) {
    return apoProepilogi;
  }
  for (const k of ['ΠΛΗ101', 'ΠΛΗ302', 'ΠΛΗ204']) {
    const vrethi = pare_xarti_mathimatos(k).enotites.find((katixeino) => katixeino.id === enotita_id);
    if (vrethi !== undefined) {
      return vrethi;
    }
  }
  return undefined;
}

/**
 * Γράφει τον ψεύτικο οδηγό μιας ενότητας ως Markdown του §5.3, ώστε ο σπόρος να γράφει
 * ακριβώς τον δρόμο που διαβάζει η οθόνη. Άγνωστη ενότητα δίνει null.
 */
export function pseudos_odigos_md(enotita_id: string, kodikos?: string): string | null {
  const odigos = ODIGOI_PSEUDOI[enotita_id] ?? ODIGOI_EPPLEON[enotita_id];
  const enotita = vreis_enotita(enotita_id, kodikos);
  if (odigos === undefined || enotita === undefined) {
    return null;
  }
  const tmimata = LEKIKIA_TMIMATON.map((kleidi) => {
    const tmima = odigos.tmimata[kleidi];
    const keimena = tmima.keimena.map((keimeno) => `${PROTHEMA_KEIMENOU}${keimeno}`).join('\n');
    return `## ${EPKEFALIDES_TMIMATON[kleidi]}\n\n${keimena}\n\n${tmima.parapompi}`;
  });
  return `# ${enotita.titlos}\n\n${tmimata.join('\n\n')}\n`;
}

/** Πρόθεμμα γραμμής περιεχομένου στο Markdown των οδηγών. */
const PROTHEMA_KEIMENOU = '- ';

/**
 * Γράφει ένα μικρό αρχικό ιστορικό συνομιλίας ως JSONL του §5.3, ώστε η οθόνη του tutor
 * να ανοίγει με ιστορικό από τα αρχεία και όχι από τη μνήμη.
 */
export function pseudos_synomilia_jsonl(enotita_id: string, kodikos?: string): string | null {
  const enotita = vreis_enotita(enotita_id, kodikos);
  if (enotita === undefined) {
    return null;
  }
  return `${JSON.stringify({
    rolos: 'tutor',
    keimeno: `Γεια σου, ρώτα με για την ενότητα «${enotita.titlos}». Απαντάω μόνο από το υλικό του μαθήματος.`,
  })}\n`;
}
